"""
Pipeline: takes a SourceItem, asks the LLM for each platform's version,
writes markdown files, and updates the dedup store + jsonl log.
"""

from __future__ import annotations

import json
import re
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Dict, Iterable, List, Optional

from .config import RepurposeConfig
from .dedup import DedupStore
from .llm_client import LLMClient, LLMCallError, LLMResponse
from .prompts import PLATFORMS, build_prompt
from .semantic_dedup import SemanticDedup
from .sources import SourceItem


# Strip ```json fences that some models add despite the rules.
_FENCE_RE = re.compile(r"^```(?:json)?\s*|\s*```$", re.MULTILINE)


def _strip_fences(text: str) -> str:
    return _FENCE_RE.sub("", text).strip()


def _safe_json(text: str) -> dict:
    cleaned = _strip_fences(text)
    # Find the first '{' and last '}' to be tolerant of stray text.
    start = cleaned.find("{")
    end = cleaned.rfind("}")
    if start == -1 or end == -1 or end <= start:
        raise ValueError("No JSON object found in model output")
    return json.loads(cleaned[start : end + 1])


def _format_markdown(platform: str, label: str, payload: dict,
                     source: SourceItem, resp: LLMResponse,
                     language: str) -> str:
    """Render the platform payload as a copy-paste-friendly markdown file."""
    lines: List[str] = []
    lines.append(f"# {label} — {source.title}")
    lines.append("")
    lines.append(f"- **Source kind:** `{source.source_kind}`")
    lines.append(f"- **Source ID:** `{source.source_id}`")
    lines.append(f"- **Language:** `{language}`")
    lines.append(f"- **Generated by:** `{resp.provider}` / `{resp.model}`")
    lines.append(f"- **Generated at:** {datetime.now(timezone.utc).isoformat()}")
    if source.source_path:
        lines.append(f"- **Source path:** `{source.source_path}`")
    lines.append("")
    lines.append("---")
    lines.append("")

    if payload.get("skipped"):
        lines.append(f"_Skipped: {payload.get('reason', 'no reason given')}_")
        return "\n".join(lines)

    for key, value in payload.items():
        lines.append(f"## {key.replace('_', ' ').title()}")
        lines.append("")
        if isinstance(value, list):
            if value and isinstance(value[0], dict):
                for i, item in enumerate(value, 1):
                    lines.append(f"### {i}")
                    for k, v in item.items():
                        lines.append(f"- **{k}:** {v}")
                    lines.append("")
            else:
                for i, item in enumerate(value, 1):
                    lines.append(f"{i}. {item}")
                lines.append("")
        else:
            lines.append(str(value))
            lines.append("")

    return "\n".join(lines)


def repurpose_one(
    item: SourceItem,
    cfg: RepurposeConfig,
    client: LLMClient,
    dedup: DedupStore,
    force: bool = False,
    platforms: Optional[Iterable[str]] = None,
    semantic_dedup: Optional["SemanticDedup"] = None,
    semantic_threshold: float = 0.85,
) -> Dict[str, dict]:
    """Repurpose a single SourceItem into all configured platforms.

    Returns a dict mapping ``platform -> result`` where result has keys
    ``ok``, ``path``, ``skipped``, ``error``, ``provider``, ``elapsed_s``.

    If ``semantic_dedup`` is provided and a similar item has already been
    repurposed, the whole item is skipped (not just per-platform), and the
    result dict will have a top-level ``__semantic_skip__`` key with the
    duplicate hit info.
    """
    platforms = list(platforms or cfg.platforms)
    # Use today's date in UTC for the output folder so re-runs on the
    # same day land together.
    date_str = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    out_dir = cfg.resolve_output(date_str, item.slug)
    out_dir.mkdir(parents=True, exist_ok=True)

    results: Dict[str, dict] = {}

    # --- Semantic dedup check (cross-item, all platforms) -----------------
    # Note: we run semantic dedup even when force=True. force bypasses the
    # per-(source_id, platform) dedup so the user can regenerate a specific
    # item, but semantic dedup is about avoiding thematic repetition across
    # DIFFERENT items — a different concern. If the user wants to bypass
    # semantic dedup too, they should use --no-semantic-dedup.
    if semantic_dedup is not None:
        is_dup, hit = semantic_dedup.is_duplicate(
            item.source_id, item.body, item.title,
            threshold=semantic_threshold,
        )
        if is_dup:
            for platform in platforms:
                results[platform] = {
                    "ok": True,
                    "skipped": True,
                    "reason": (
                        f"semantic duplicate of {hit.source_id} "
                        f"({hit.method} sim={hit.similarity})"
                    ),
                }
            results["__semantic_skip__"] = {
                "duplicate_of": hit.source_id,
                "similarity": hit.similarity,
                "method": hit.method,
            }
            _append_log(cfg, item, "semantic_skip", ok=True, **{
                "duplicate_of": hit.source_id,
                "similarity": hit.similarity,
                "method": hit.method,
            })
            # Write a manifest so the user sees why we skipped.
            manifest_path = out_dir / "manifest.json"
            manifest_path.write_text(
                json.dumps({
                    "source": {
                        "kind": item.source_kind,
                        "id": item.source_id,
                        "title": item.title,
                        "truncated": item.truncated,
                    },
                    "skipped": True,
                    "skip_reason": "semantic_duplicate",
                    "duplicate_of": hit.source_id,
                    "similarity": hit.similarity,
                    "method": hit.method,
                    "generated_at": datetime.now(timezone.utc).isoformat(),
                }, indent=2, ensure_ascii=False),
                encoding="utf-8",
            )
            return results
        # Not a duplicate: register so future items can compare against it.
        semantic_dedup.register(item.source_id, item.body, item.title)

    for platform in platforms:
        if platform not in PLATFORMS:
            results[platform] = {"ok": False, "error": f"unknown platform {platform}"}
            continue

        if not force and dedup.seen(item.source_id, platform, cfg.language):
            results[platform] = {
                "ok": True,
                "skipped": True,
                "reason": "already repurposed (use --force to redo)",
            }
            continue

        system, user = build_prompt(
            platform=platform,
            source_kind=item.source_kind,
            title=item.title,
            body=item.body,
            language=cfg.language,
            truncated=item.truncated,
        )

        try:
            resp = client.chat(system, user)
        except LLMCallError as exc:
            results[platform] = {"ok": False, "error": str(exc)}
            _append_log(cfg, item, platform, ok=False, error=str(exc))
            continue

        try:
            payload = _safe_json(resp.text)
        except ValueError as exc:
            err = f"JSON parse error: {exc}; raw[:200]={resp.text[:200]!r}"
            results[platform] = {"ok": False, "error": err}
            _append_log(cfg, item, platform, ok=False, error=err,
                        provider=resp.provider, model=resp.model)
            continue

        out_path = out_dir / f"{platform}.md"
        out_path.write_text(
            _format_markdown(platform, PLATFORMS[platform]["label"], payload,
                             item, resp, cfg.language),
            encoding="utf-8",
        )
        dedup.mark(item.source_id, platform, cfg.language, str(out_path))
        _append_log(cfg, item, platform, ok=True, path=str(out_path),
                    provider=resp.provider, model=resp.model,
                    elapsed_s=resp.elapsed_s, skipped=bool(payload.get("skipped")))

        results[platform] = {
            "ok": True,
            "path": str(out_path),
            "provider": resp.provider,
            "model": resp.model,
            "elapsed_s": resp.elapsed_s,
            "skipped": bool(payload.get("skipped")),
        }

    # Write a manifest for this source item.
    manifest_path = out_dir / "manifest.json"
    manifest_path.write_text(
        json.dumps(
            {
                "source": {
                    "kind": item.source_kind,
                    "id": item.source_id,
                    "title": item.title,
                    "language": item.language,
                    "created_at": item.created_at,
                    "source_path": item.source_path,
                    "truncated": item.truncated,
                },
                "config": {
                    "language": cfg.language,
                    "platforms": platforms,
                },
                "results": results,
                "generated_at": datetime.now(timezone.utc).isoformat(),
            },
            indent=2,
            ensure_ascii=False,
        ),
        encoding="utf-8",
    )

    return results


def repurpose_batch(
    items: Iterable[SourceItem],
    cfg: RepurposeConfig,
    client: LLMClient,
    dedup: DedupStore,
    force: bool = False,
    platforms: Optional[Iterable[str]] = None,
    on_progress=None,
    semantic_dedup: Optional[SemanticDedup] = None,
    semantic_threshold: float = 0.85,
) -> List[Dict[str, dict]]:
    """Repurpose multiple items. ``on_progress(idx, total, item, results)``
    is called after each item so the CLI can print a live status.

    If ``semantic_dedup`` is provided, items that are semantically similar
    to a previously-processed item will be skipped entirely.
    """
    items = list(items)
    all_results: List[Dict[str, dict]] = []
    for idx, item in enumerate(items, 1):
        results = repurpose_one(
            item, cfg, client, dedup, force=force,
            platforms=platforms,
            semantic_dedup=semantic_dedup,
            semantic_threshold=semantic_threshold,
        )
        all_results.append({"item": item, "results": results})
        if on_progress:
            try:
                on_progress(idx, len(items), item, results)
            except Exception:  # noqa: BLE001
                pass
    return all_results


def _append_log(cfg: RepurposeConfig, item: SourceItem, platform: str,
                ok: bool, **extra) -> None:
    entry = {
        "ts": datetime.now(timezone.utc).isoformat(),
        "source_id": item.source_id,
        "source_kind": item.source_kind,
        "title": item.title,
        "platform": platform,
        "language": cfg.language,
        "ok": ok,
        **extra,
    }
    with cfg.log_path.open("a", encoding="utf-8") as f:
        f.write(json.dumps(entry, ensure_ascii=False) + "\n")
